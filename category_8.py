facts = set()
rules = []
def add_fact(fact):
    facts.add(fact)
def add_rule(conditions, conclusion):
    rules.append((conditions, conclusion))
def forward_chaining():
    changed = True
    while changed:
        changed = False
        for conditions, conclusion in rules:
            if all(condition in facts for condition in conditions):
                if conclusion not in facts:
                    facts.add(conclusion)
                    changed = True
def backward_chaining(goal, visited=None):
    if visited is None:
        visited = set()
    if goal in facts:
        return True
    if goal in visited:
        return False
    visited.add(goal)
    for conditions, conclusion in rules:
        if conclusion == goal:
            if all(backward_chaining(condition, visited)
                   for condition in conditions):
                return True
    return False
